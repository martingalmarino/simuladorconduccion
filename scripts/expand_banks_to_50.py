def merge(bank_name: str, new_qs: list[dict], title: str, coverage: str) -> None:
    path = ROOT / "data" / f"{bank_name}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    existing_ids = {q["id"] for q in data["questions"]}
    for item in new_qs:
        if item["id"] in existing_ids:
            raise SystemExit(f"Duplicate id {item['id']}")
    data["title"] = title
    data["coverage"] = coverage
    data["questions"] = data["questions"] + new_qs
    if len(data["questions"]) != 50:
        raise SystemExit(f"{bank_name} expected 50, got {len(data['questions'])}")
    # distribute correct option positions roughly
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {bank_name}: {len(data['questions'])} questions")


